func (r *rawBackupSchedule) Get() ConfigBackupSchedule {
	schedule := r.GetSchedule()
	storage := r.GetStorage()
	mode := r.GetMode()
	compress := r.GetCompress()
	vmids := r.GetVMIDs()
	all := r.GetAll()
	pool := r.GetPool()
	enabled := r.GetEnabled()
	node := r.GetNode()
	mailto := r.GetMailto()
	mailNotification := r.GetMailNotification()
	notesTemplate := r.GetNotesTemplate()
	pruneBackups := r.GetPruneBackups()
	protected := r.GetProtected()
	comment := r.GetComment()
	config := ConfigBackupSchedule{
		ID:               r.id,
		Schedule:         &schedule,
		Storage:          &storage,
		Mode:             &mode,
		Compress:         &compress,
		VMIDs:            &vmids,
		All:              &all,
		Pool:             &pool,
		Enabled:          &enabled,
		Node:             &node,
		Mailto:           &mailto,
		MailNotification: &mailNotification,
		NotesTemplate:    &notesTemplate,
		PruneBackups:     &pruneBackups,
		Protected:        &protected,
		Comment:          &comment,
	}
	return config
}

